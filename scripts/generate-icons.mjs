// Regenerates src/lib/icon-data.ts from the Lucide icon set (ISC licence).
// Run with: node scripts/generate-icons.mjs
// Add a name to ICONS below, regenerate, and commit the result.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const ICONS = [
  'menu',
  'x',
  'sun',
  'moon',
  'monitor',
  'arrow-right',
  'arrow-down',
  'messages-square',
  'workflow',
  'server',
  'app-window',
  'lock',
  'house',
  'rotate-cw',
];

const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve('lucide-static/package.json')), 'icons');

const entries = ICONS.map((name) => {
  const svg = readFileSync(join(iconsDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  return `  '${name}': ${JSON.stringify(inner)},`;
});

const out = `// Generated by scripts/generate-icons.mjs from Lucide (https://lucide.dev, ISC licence).
// Do not edit by hand.
export const ICON_BODIES = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_BODIES;
`;

writeFileSync(new URL('../src/lib/icon-data.ts', import.meta.url), out);
console.log(`Wrote ${ICONS.length} icons`);
